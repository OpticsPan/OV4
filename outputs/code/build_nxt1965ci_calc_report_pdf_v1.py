TOKEN_RE = re.compile(r"(\*\*[^*]+?\*\*|\*[^*]+?\*|_\{[^{}]+\}|\^\{[^{}]+\})")


def esc(text) -> str:
    return html.escape(str(text), quote=True)


def rich(text) -> str:
    out = []
    for part in TOKEN_RE.split(str(text)):
        if not part:
            continue
        if part.startswith("**") and part.endswith("**"):
            out.append(f"<strong>{rich(part[2:-2])}</strong>")
        elif part.startswith("*") and part.endswith("*"):
            out.append(f"<em>{esc(part[1:-1])}</em>")
        elif part.startswith("_{") and part.endswith("}"):
            out.append(f"<sub>{esc(part[2:-1])}</sub>")
        elif part.startswith("^{") and part.endswith("}"):
            out.append(f"<sup>{esc(part[2:-1])}</sup>")
        else:
            out.append(esc(part))
    return "".join(out)


def render_table(headers: list, rows: list, widths: list,
                 center_cols=(), right_cols=(), bold_cols=(0,), compact=False) -> str:
    ths = []
    for i, (h, w) in enumerate(zip(headers, widths)):
        al = "center" if i in center_cols else ("right" if i in right_cols else "left")
        ths.append(f'<th style="width:{w};text-align:{al}">{rich(h)}</th>')
    trs = []
    for row in rows:
        is_total = isinstance(row, dict)
        vals = row["vals"] if is_total else row
        tr_cls = f' class="{row.get("cls", "")}"' if is_total else ""
        tds = []
        for i, val in enumerate(vals):
            al = "center" if i in center_cols else ("right" if i in right_cols else "left")
            fw = "font-weight:bold;color:#102A43;" if (i in bold_cols or is_total) else ""
            tds.append(f'<td style="text-align:{al};{fw}">{rich(val)}</td>')
        trs.append(f"<tr{tr_cls}>{''.join(tds)}</tr>")
    cls = "data-tbl compact" if compact else "data-tbl"
    return f'<table class="{cls}"><thead><tr>{"".join(ths)}</tr></thead><tbody>{"".join(trs)}</tbody></table>'


