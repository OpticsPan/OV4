def find_chrome() -> Path:
    for c in (
        Path(r"C:\Program Files\Google\Chrome\Application\chrome.exe"),
        Path(r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"),
        shutil.which("chrome"),
        shutil.which("msedge"),
    ):
        if c and Path(c).is_file():
            return Path(c)
    raise RuntimeError("Chrome/Edge not found")


def render_pdf(markup: str, work: Path, tag: str) -> Path:
    hp = work / f"calc-{tag}.html"
    pp = work / f"calc-{tag}.pdf"
    hp.write_text(markup, encoding="utf-8")
    if pp.exists():
        pp.unlink()
    cmd = [
        str(find_chrome()), "--headless=new", "--disable-gpu", "--disable-extensions",
        "--no-first-run", "--no-default-browser-check", "--allow-file-access-from-files",
        "--no-pdf-header-footer", f"--user-data-dir={work / ('prof-' + tag)}",
        f"--print-to-pdf={pp}", hp.as_uri(),
    ]
    res = subprocess.run(cmd, capture_output=True, timeout=120,
                         creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    if res.returncode or not pp.is_file():
        raise RuntimeError(res.stderr.decode("utf-8", "replace"))
    return pp


def locate_headings(doc: fitz.Document, chapters: list):
    ch_pages, sec_pages = {}, {}
    toc = [[1, "封面与目录", 1]]
    sec_lookup = {st.split()[0]: (ch["id"], st) for ch in chapters for st in ch["sections"]}
    found_ch, found_sec = set(), set()

    for p in doc:
        if p.number == 0:
            continue
        pg_num = p.number + 1
        blocks = p.get_text("dict", flags=fitz.TEXTFLAGS_DICT & ~fitz.TEXT_PRESERVE_IMAGES)["blocks"]
        for b in blocks:
            for line in b.get("lines", []):
                spans = line.get("spans", [])
                if not spans:
                    continue
                txt = "".join(sp["text"] for sp in spans).strip()
                max_sz = max(sp["size"] for sp in spans)
                m_ch = re.match(r"^第\s*(\d+)\s*章", txt)
                if m_ch and max_sz >= 11.0:
                    cid = f"ch-{int(m_ch.group(1))}"
                    if cid not in found_ch:
                        for ch in chapters:
                            if ch["id"] == cid:
                                ch_pages[cid] = pg_num
                                toc.append([1, ch["title"], pg_num])
                                found_ch.add(cid)
                                break
                m_sec = re.match(r"^(\d+\.\d+)\s+", txt)
                if m_sec and 9.2 <= max_sz < 11.0:
                    code = m_sec.group(1)
                    if code in sec_lookup and code not in found_sec:
                        cid, full_st = sec_lookup[code]
                        sec_pages[(cid, full_st)] = pg_num
                        toc.append([2, full_st, pg_num])
                        found_sec.add(code)
    missing = [ch["id"] for ch in chapters if ch["id"] not in found_ch]
    if missing:
        raise RuntimeError(f"Missing chapters: {missing}")
    return ch_pages, sec_pages, toc


def main():
    if not LEDGER_PATH.is_file():
        raise FileNotFoundError(f"Run calc_nxt1965ci_overlay_budget_audit_v1.py first: missing {LEDGER_PATH}")
    L = json.loads(LEDGER_PATH.read_text(encoding="utf-8"))
    for p in (REF009_FIG3, CHART_DIR / "fig1_ref009_share_audit.png",
              CHART_DIR / "fig2_machine_recovery.png",
              CHART_DIR / "fig3_corr_and_montecarlo.png",
              CHART_DIR / "fig4_tornado_sensitivity.png"):
        if not p.is_file():
            raise FileNotFoundError(f"Missing figure: {p}")

    chapters = build_chapters(L)
    WORK_DIR.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="calc-", dir=WORK_DIR, ignore_cleanup_errors=True) as td:
        work = Path(td)
        p1 = render_pdf(compose_html(L, chapters, {}, {}), work, "p1")
        with fitz.open(p1) as d1:
            ch_p1, sec_p1, _ = locate_headings(d1, chapters)
        p2 = render_pdf(compose_html(L, chapters, ch_p1, sec_p1), work, "p2")
        with fitz.open(p2) as d2:
            ch_p2, sec_p2, toc = locate_headings(d2, chapters)
            assert ch_p2 == ch_p1, f"Page shift: {ch_p1} -> {ch_p2}"
            assert ch_p2["ch-1"] == 2, f"Cover+TOC spilled onto p.2! ch-1 on p.{ch_p2['ch-1']}"

            full_txt = "\n".join(pg.get_text("text") for pg in d2)
            assert "{" not in full_txt and "}" not in full_txt, "Raw brace leaked!"
            assert "`" not in full_txt, "Raw backtick leaked!"

            d2.set_toc(toc)
            d2.set_metadata({
                "title": "ASML NXT:1965Ci 指标规格分配计算报告 (v1)",
                "subject": "12-Subsystem Overlay Budget Derivation, Source Audit, DCO/SMO/MMO Recovery & Monte Carlo",
                "author": "OpticsPan / OV4",
            })
            OUT_PDF.parent.mkdir(parents=True, exist_ok=True)
            d2.save(OUT_PDF, garbage=3, deflate=True)
            total_pages = len(d2)

            if PREV_DIR.exists():
                shutil.rmtree(PREV_DIR)
            PREV_DIR.mkdir(parents=True, exist_ok=True)
            for pg in d2:
                pg.get_pixmap(dpi=140).save(PREV_DIR / f"page_{pg.number + 1:02d}.png")

    print(f"[CALC PDF OK] {OUT_PDF.name} | {total_pages} pages | {len(toc)} bookmarks")
    for ch in chapters:
        print(f"  p.{ch_p2[ch['id']]:2d}  {ch['title']}")


